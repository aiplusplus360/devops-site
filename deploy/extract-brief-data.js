/* Writes the source-data appendix the content subagents read, so their brief and
   the site can never disagree about names, ids or available technologies.
   Run:  node deploy/extract-brief-data.js  */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
global.window = global;
require(path.join(ROOT, "assets/js/config.js"));
require(path.join(ROOT, "assets/js/data.js"));
require(path.join(ROOT, "assets/js/tech.js"));

const S = window.SERVICES;
const C = window.CATEGORY_ORDER;
const T = window.TECHNOLOGIES;

let out = "";
out += "# Source data (appendix to the brief)\n\n";
out += "Generated by `deploy/extract-brief-data.js` from `assets/js/data.js` and\n";
out += "`assets/js/tech.js`. Do not edit by hand.\n\n";
out += "## Services by category\n\n";

for (const c of C) {
  const list = S.filter((s) => s.category === c);
  out += "### " + c + " — " + list.length + " services\n\n";
  for (const s of list) {
    out += "- **`" + s.id + "`** — " + s.name + "\n";
    out += "  - icon: `" + s.icon + "`" + (s.featured ? "  (featured on homepage)" : "") + "\n";
    out += "  - summary: " + s.summary + "\n";
    out += "  - current bullets:\n";
    s.bullets.forEach((b) => (out += "    - " + b + "\n"));
  }
  out += "\n";
}

out += "## Valid technology ids\n\n";
out += "Use ONLY these exact ids in a `stack` array. Anything else fails validation.\n\n";
for (const g of window.TECH_GROUP_ORDER) {
  const list = T.filter((t) => t.group === g);
  out += "- **" + g + "** — " + list.map((t) => "`" + t.id + "`").join(", ") + "\n";
}
out += "\n" + T.length + " ids total.\n\n";

out += "## All 40 service ids (use for `related`)\n\n";
out += S.map((s) => "`" + s.id + "`").join(", ") + "\n\n";

out += "## Valid icon keys\n\n";
out += "Use ONLY these in `includes[].icon` and anywhere an icon is referenced.\n";
out += "Each is a 24x24 stroke icon already drawn in the site's own style.\n\n";
out += Object.keys(window.ICONS).map((k) => "`" + k + "`").join(", ") + "\n\n";
out += Object.keys(window.ICONS).length + " icons total.\n\n";

out += "## Site-level numbers you may reference\n\n";
out += "From `assets/js/config.js` — keep consistent with these:\n\n";
window.SITE.stats.forEach((s) => (out += "- " + s.value + " " + s.label + "\n"));

const dest = path.join(ROOT, "client/src/content/_source-data.md");
fs.writeFileSync(dest, out);
console.log("wrote client/src/content/_source-data.md");
console.log("  categories: " + C.length + ", services: " + S.length + ", tech ids: " + T.length);
